class FeatureRegistry:
    def __init__(self, registry_path: Optional[Path] = None):
        self.registry_path = registry_path or REGISTRY_PATH
        self.registry_path.parent.mkdir(parents=True, exist_ok=True)
        self._features: List[FeatureSpec] = []
        self._load()

    def _load(self):
        if self.registry_path.exists():
            data = json.loads(self.registry_path.read_text(encoding="utf-8"))
            self._features = [FeatureSpec(**item) for item in data]
            self._features.extend(EXTENDED_FEATURES)
        else:
            self._features = list(DEFAULT_FEATURES)
            self._features.extend(EXTENDED_FEATURES)
            self.save()

    def save(self):
        data = [asdict(feature) for feature in self._features]
        self.registry_path.write_text(json.dumps(data, indent=2), encoding="utf-8")

    def list_features(self) -> List[dict]:
        return [asdict(feature) for feature in self._features]

    def get_feature(self, feature_id: str) -> Optional[dict]:
        for feature in self._features:
            if feature.feature_id == feature_id:
                return asdict(feature)
        return None

    def add_feature(self, feature: FeatureSpec):
        existing = self.get_feature(feature.feature_id)
        if existing is not None:
            raise ValueError(f"Feature already exists: {feature.feature_id}")
        self._features.append(feature)
        self.save()
